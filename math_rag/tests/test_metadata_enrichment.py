def test_changed_source_hash_invalidates_only_changed_file_cache(tmp_path):
    corpus = tmp_path / "corpus"
    corpus.mkdir()
    changed = corpus / "changed.md"
    unchanged = corpus / "unchanged.md"
    changed.write_text("# Changed\n\nMabuchi energy.\n", encoding="utf-8")
    unchanged.write_text("# Unchanged\n\nToric geometry.\n", encoding="utf-8")
    cache = MetadataEnrichmentCache(tmp_path / "cache")

    chunks, _ = load_corpus(corpus, enrich_metadata=True, enrichment_cache_dir=cache.cache_dir)
    by_source = {chunk.source_path: chunk for chunk in chunks}
    for path in (changed, unchanged):
        payload = json.loads(cache.cache_path_for_source(path).read_text(encoding="utf-8"))
        payload["enrichments_by_chunk_id"][by_source[str(path)].chunk_id]["semantic_title"] = f"cached {path.name}"
        cache.cache_path_for_source(path).write_text(json.dumps(payload), encoding="utf-8")
    changed.write_text("# Changed\n\nMabuchi energy changed.\n", encoding="utf-8")

    refreshed_chunks, warnings = load_corpus(corpus, enrich_metadata=True, enrichment_cache_dir=cache.cache_dir)
    refreshed_by_source = {chunk.source_path: chunk for chunk in refreshed_chunks}

    assert warnings == []
    assert refreshed_by_source[str(changed)].metadata["enrichment"]["semantic_title"] != "cached changed.md"
    assert refreshed_by_source[str(unchanged)].metadata["enrichment"]["semantic_title"] == "cached unchanged.md"


