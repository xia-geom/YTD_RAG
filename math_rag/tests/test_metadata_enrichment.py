def test_agent_json_enrichment_preserves_chunk_fields_and_merges_metadata(tmp_path):
    corpus = tmp_path / "corpus"
    corpus.mkdir()
    note = corpus / "notes.md"
    note.write_text("# Notes\n\nMabuchi energy and weak geodesics.\n", encoding="utf-8")
    base_chunks, _ = load_corpus(corpus)
    jsonl = tmp_path / "agent.jsonl"
    _write_agent_jsonl(
        jsonl,
        [
            {
                "chunk_id": base_chunks[0].chunk_id,
                "source_path": base_chunks[0].source_path,
                "semantic_title": "Agent title for Mabuchi",
                "retrieval_summary": "Agent summary for weak geodesic retrieval.",
                "concept_tags": ["agent_mabuchi", "finite_energy_geodesic"],
                "depends_on_previous": True,
                "agent_notes": "Generated by an offline agent.",
                "source_role": "navigation_note",
            }
        ],
    )

    enriched_chunks, warnings = load_corpus(
        corpus,
        enrich_metadata=True,
        enrichment_cache_dir=tmp_path / "cache",
        enrichment_backend="agent_json_v1",
        agent_enrichment_jsonl=jsonl,
    )

    assert warnings == []
    enriched = enriched_chunks[0]
    assert enriched.chunk_id == base_chunks[0].chunk_id
    assert enriched.content == base_chunks[0].content
    assert enriched.line_start == base_chunks[0].line_start
    assert enriched.line_end == base_chunks[0].line_end
    assert enriched.chunk_type == base_chunks[0].chunk_type
    enrichment = enriched.metadata["enrichment"]
    assert enrichment["semantic_title"] == "Agent title for Mabuchi"
    assert enrichment["retrieval_summary"] == "Agent summary for weak geodesic retrieval."
    assert "agent_mabuchi" in enrichment["concept_tags"]
    assert enrichment["depends_on_previous"] is True
    assert enrichment["agent_notes"] == "Generated by an offline agent."
    assert enrichment["source_role"] == "project_note"


